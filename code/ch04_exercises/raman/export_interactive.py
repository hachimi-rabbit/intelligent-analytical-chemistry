"""Export small, traceable result records for the offline browser module."""
import argparse
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[3]
DEFAULT_OUTPUT = Path(__file__).resolve().parent / "outputs"
DEFAULT_TARGET = ROOT / "assets/js/ch04-results.js"


def build_payload(output):
    output = Path(output)
    metrics = json.loads((output / "metrics.json").read_text(encoding="utf-8"))
    rows = pd.read_csv(output / "row_oof.csv")
    rows = rows[rows.model.eq("Dummy")]
    folds = {}
    for strategy, group in rows.groupby("cv_strategy"):
        folds[strategy] = [
            {"id": sid, "folds": h.sort_values("scan_id").fold.astype(int).tolist()}
            for sid, h in group.groupby("specimen_id")
        ]
    return {
        "status": "教学模拟；预计算模型结果，浏览器不重新训练",
        "seed": metrics["seed"], "folds": folds,
        "classes": metrics["class_order"], "cv": metrics["cv_results"],
        "holdout": metrics["paired_holdout"],
        "panel": pd.read_csv(output / "preprocessing_panel.csv")[[
            "seed", "model", "evaluation", "macro_f1", "n_specimens"
        ]].to_dict("records"),
        "panel_predictions": pd.read_csv(output / "panel_sample_predictions.csv")[[
            "seed", "model", "instrument", "specimen_id", "true_class", "predicted_class"
        ]].to_dict("records"),
        "extensions": json.loads((output / "extensions_summary.json").read_text(encoding="utf-8")),
    }


def render_script(payload):
    return (
        "/* Generated by export_interactive.py; do not hand-edit numerical results. */\n"
        + "(function(root){'use strict'; var data="
        + json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
        + "; if(typeof module==='object' && module.exports){module.exports=data;}else{root.IAC_CH04_DATA=data;}})(typeof window!=='undefined'?window:this);\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT,
                        help="Directory containing Python result CSV/JSON files")
    parser.add_argument("--target", type=Path, default=DEFAULT_TARGET)
    args = parser.parse_args()
    script = render_script(build_payload(args.output))
    args.target.parent.mkdir(parents=True, exist_ok=True)
    args.target.write_text(script, encoding="utf-8")
    print(args.target)


if __name__ == "__main__":
    main()
