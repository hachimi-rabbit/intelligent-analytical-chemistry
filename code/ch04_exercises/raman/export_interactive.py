"""Export small, traceable result records for the offline browser module."""
from pathlib import Path
import json
import pandas as pd


def main():
    repo=Path(__file__).resolve().parents[3]
    output=Path(__file__).parent/"outputs"
    metrics=json.loads((output/"metrics.json").read_text())
    rows=pd.read_csv(output/"row_oof.csv")
    rows=rows[rows.model.eq("Dummy")]
    folds={}
    for strategy,g in rows.groupby("cv_strategy"):
        folds[strategy]=[{"id":sid,"folds":h.sort_values("scan_id").fold.astype(int).tolist()}
                         for sid,h in g.groupby("specimen_id")]
    payload={"status":"教学模拟；预计算模型结果，浏览器不重新训练", "seed":metrics["seed"],
             "folds":folds,"classes":metrics["class_order"],"cv":metrics["cv_results"],
             "holdout":metrics["paired_holdout"],
             "panel":pd.read_csv(output/"preprocessing_panel.csv")[["seed","model","evaluation","macro_f1","n_specimens"]].to_dict("records"),
             "panel_predictions":pd.read_csv(output/"panel_sample_predictions.csv")[["seed","model","instrument","specimen_id","true_class","predicted_class"]].to_dict("records"),
             "extensions":json.loads((output/"extensions_summary.json").read_text())}
    target=repo/"assets/js/ch04-results.js"
    target.write_text("/* Generated by export_interactive.py; do not hand-edit numerical results. */\n"
                      +"(function(root){'use strict'; var data="+json.dumps(payload,ensure_ascii=False,separators=(",",":"))
                      +"; if(typeof module==='object' && module.exports){module.exports=data;}else{root.IAC_CH04_DATA=data;}})(typeof window!=='undefined'?window:this);\n",encoding="utf-8")
    print(target)


if __name__=="__main__":
    main()
